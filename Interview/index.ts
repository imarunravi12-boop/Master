// Maximum value in an array
let numbers = [6,5,2,3,10,2,7,8,9]
let maxvalue = numbers[0];
for (let i =1; i < numbers.length;i++){
    if(numbers[i] > maxvalue) {
        maxvalue = numbers[i]
    };
};
console.log(maxvalue)


